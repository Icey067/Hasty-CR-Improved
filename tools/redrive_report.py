"""Write reports/redrive_fidelity.md from the re-drive bench runs.

    py -3.12 tools/redrive_report.py --main b2000 \
        --elixir se_default se6000 se6000_pump

Inputs are reports/redrive/<name>.jsonl from tools/redrive_bench.py.
"""
from __future__ import annotations

import argparse
import collections
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "reports" / "redrive"


def load(name):
    return [json.loads(line) for line in (RUNS / f"{name}.jsonl").open(encoding="utf-8")]


def forced_rates(rows):
    counts = collections.Counter()
    plays = sum(r["plays"] for r in rows)
    for r in rows:
        counts.update(r["forced"])
    return {k: 100 * v / max(1, plays) for k, v in counts.items()}, plays


def early_refusals(rows, ticks=600):
    return sum(1 for r in rows for e in r["elixir_events"] if e[0] < ticks)


def card_lift(rows, min_sides=60):
    excess, by_card = [], collections.defaultdict(list)
    for r in rows:
        for side in ("team", "opponent"):
            x = r["engine_crowns"][side] - r["recorded_crowns"][side]
            excess.append(x)
            for card in r["decks"][side]:
                by_card[card].append(x)
    mean = sum(excess) / len(excess)
    sd = (sum((x - mean) ** 2 for x in excess) / len(excess)) ** 0.5
    ranked = sorted(((sum(v) / len(v) - mean, len(v), k)
                     for k, v in by_card.items() if len(v) >= min_sides), reverse=True)
    return mean, sd, ranked


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--main", default="b2000")
    ap.add_argument("--elixir", nargs=3, default=["se_default", "se6000", "se6000_pump"])
    ap.add_argument("--out", type=Path, default=ROOT / "reports" / "redrive_fidelity.md")
    args = ap.parse_args()

    base, six, pump = (load(n) for n in args.elixir)
    rows = [r for r in load(args.main) if r["ok"]]
    L = []
    w = L.append
    w("# Re-drive fidelity: IL_Replay through our engine\n")
    w("Generated by `tools/redrive_bench.py` + `tools/redrive_report.py`. Each recorded match is played "
      "through `sim/` with its recorded decks, level, card plays, ticks and tiles. A play the engine "
      "refuses is counted, then forced so the match goes on. Sample: the first loadable Ranked / Ladder "
      "/ 1v1 matches of the corpus, so runs are paired match for match.\n")
    w(f"## 1. Elixir: two fixes, measured ({len(base)} matches)\n")
    w("An elixir refusal: the real player could afford the card and our engine said no. Per 100 plays:\n")
    w("| engine | elixir refusals | in first 30 s |")
    w("|---|---|---|")
    for label, rs in (("as shipped (start 5, no pump income)", base), ("start elixir 6", six),
                      ("start 6 + Elixir Collector income", pump)):
        w(f"| {label} | {forced_rates(rs)[0].get('elixir', 0):.2f} | {early_refusals(rs)} |")
    w("")
    w("- **Start elixir.** At 5 there were refusals in the opening 30 s, mean shortfall 0.43 elixir; at 6 "
      "none, and 7 (control) changed nothing further (0.94 -> 0.91 per 100). The replay cannot tell a "
      "start of 6 from regen running ~2.8 s before replay tick 0; they play the same. RoyaleSim lists 6 "
      "as measured. Applied in the re-drive only; **not yet the engine default** - that changes the "
      "training environment and is the owner's call.")
    w("- **Elixir Collector.** The engine read none of `ManaCollectAmount`, `ManaGenerateTimeMs`, "
      "`ManaOnDeath`, `ManaOnDeathForOpponent`. Sides running a Collector were refused 4.0 times per "
      "match, every other side 0.02; with the client's values now in `sim/match.py`, 0.27 and 0.007.\n")

    wa = sum(r["winner_agree"] for r in rows) / len(rows)
    ca = sum(r["crowns_agree"] for r in rows) / len(rows)
    e3 = sum(1 for r in rows if 3 in r["engine_crowns"].values())
    r3 = sum(1 for r in rows if 3 in r["recorded_crowns"].values())
    mean, sd, ranked = card_lift(rows)
    w(f"## 2. Endings ({len(rows)} matches)\n")
    w(f"- Winner agreement **{wa:.1%}**, exact crowns {ca:.1%}: a coin flip. Small errors compound over "
      "three minutes, so the ending alone is a weak signal; refusals and the ranking below are the strong ones.")
    w(f"- Three-crown matches: engine **{e3}**, recorded {r3}. Towers fall far too often in our engine.")
    w(f"- Mean excess crowns per side (engine minus recorded): **{mean:+.3f}**.\n")
    w("## 3. Per-card ranking: the engine fix list\n")
    w("Mean excess crowns taken by the sides running a card, minus the overall mean; cards on >= 60 "
      "sides. Positive: that side does better in our engine than it did in the game. **Confounded** - a "
      "deck's cards travel together, so a card can ride on the one actually at fault. Each needs an "
      "isolated check before anything is changed.\n")
    w("| card | sides | lift | z |")
    w("|---|---|---|---|")
    for d, n, k in ranked[:20]:
        w(f"| {k} | {n} | {d:+.3f} | {d / (sd / math.sqrt(n)):+.1f} |")
    w("| ... | | | |")
    for d, n, k in ranked[-20:]:
        w(f"| {k} | {n} | {d:+.3f} | {d / (sd / math.sqrt(n)):+.1f} |")
    w("")
    w("Pattern: the tower-chip cards (Rocket, Earthquake, Poison, Goblin Drill, Mighty Miner, Tesla) "
      "under-take; splash and swarm troops (Witch, Mega Knight, Executioner, Night Witch, Bats, Minion "
      "Horde, Skeleton Army) over-take. First suspects: spell and burrower damage to crown towers, and "
      "splash against swarms.\n")
    rates, plays = forced_rates(rows)
    w(f"## 4. All refusals per 100 plays ({plays:,} plays)\n")
    for k, v in sorted(rates.items(), key=lambda kv: -kv[1]):
        w(f"- {k}: {v:.2f}")
    w("\n`hand` includes the unknown starting order. `dropped` = no legal tile within 2 tiles of the "
      "recorded one (our deploy-area rule or the frame), worth its own check.")
    args.out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
